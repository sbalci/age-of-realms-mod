// Offline coastline masks. Rebuild with: node tools/build-geography.mjs
import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const read = name => JSON.parse(fs.readFileSync(new URL(`assets/thirdparty/natural-earth/ne_50m_${name}.geojson`, root)));
const regions = { anatolia: [25, 35, 46, 43], mediterranean: [-11, 29, 43, 47], world: [-180, -60, 180, 85] };
const N = 256, masks = {};
for (const [name, bounds] of Object.entries(regions)) {
  const [west, south, east, north] = bounds, mask = new Uint8Array(N * N);
  for (const [data, value] of [[read('land'), 1], [read('lakes'), 0]]) {
    for (const feature of data.features) {
      const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
      for (const rings of polygons) for (let y = 0; y < N; y++) {
        const lat = north - (y + .5) / N * (north - south), crossings = [];
        for (const ring of rings) for (let j = 1; j < ring.length; j++) {
          const [ax, ay] = ring[j - 1], [bx, by] = ring[j];
          if ((ay > lat) !== (by > lat)) crossings.push(ax + (lat - ay) / (by - ay) * (bx - ax));
        }
        crossings.sort((a, b) => a - b);
        for (let k = 0; k + 1 < crossings.length; k += 2) {
          const start = Math.max(0, Math.ceil((crossings[k] - west) / (east - west) * N - .5));
          const end = Math.min(N, Math.ceil((crossings[k + 1] - west) / (east - west) * N - .5));
          if (end > start) mask.fill(value, y * N + start, y * N + end);
        }
      }
    }
  }
  const runs = []; let previous = 0, count = 0;
  for (const v of mask) { if (v === previous) count++; else { runs.push(count); previous = v; count = 1; } } runs.push(count);
  masks[name] = { bounds, n: N, runs };
}
fs.writeFileSync(new URL('game/js/geography-data.js', root), `// Made with Natural Earth (public domain). Generated by tools/build-geography.mjs.\n'use strict';\nconst GEOGRAPHY_DATA = ${JSON.stringify(masks)};\n`);
console.log('Built three 256×256 land/lake masks.');
