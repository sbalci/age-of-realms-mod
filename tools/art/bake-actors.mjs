// Bake animated sprites from CC0 rigs and project-authored dress, equipment, wildlife and vehicles.
import { chromium } from '@playwright/test';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..'),out=path.join(root,'game/art/actors');
const mime={'.html':'text/html','.js':'text/javascript','.png':'image/png','.glb':'model/gltf-binary','.fbx':'application/octet-stream'};
const server=http.createServer((req,res)=>{
  let file;try{file=path.resolve(root,'.'+decodeURIComponent(new URL(req.url,'http://localhost').pathname));}catch{res.writeHead(400).end();return;}
  if(!file.startsWith(root+path.sep)){res.writeHead(403).end();return;}
  fs.readFile(file,(e,d)=>e?res.writeHead(404).end():res.writeHead(200,{'Content-Type':mime[path.extname(file)]||'application/octet-stream'}).end(d));
}).listen(0,'127.0.0.1');
await new Promise(r=>server.once('listening',r));let browser;
try{
  browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage();page.on('pageerror',e=>console.error(e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/tools/art/actors-bake.html`);
  await page.waitForFunction(()=>window.ready);
  const only=process.argv.indexOf('--only'),keys=only<0?await page.evaluate(()=>window.actorKeys):process.argv[only+1].split(',');
  fs.mkdirSync(out,{recursive:true});let manifest={};
  const manifestPath=path.join(out,'manifest.js');
  if(only>=0&&fs.existsSync(manifestPath))manifest=vm.runInNewContext(fs.readFileSync(manifestPath,'utf8')+';ACTOR_ART');
  for(const key of keys){
    const {png,mask,nonEmpty,sourceClips,bones,...meta}=await page.evaluate(k=>window.bakeActor(k),key);
    if(process.argv.includes('--inspect'))console.log(JSON.stringify({key,sourceClips,bones}));
    if(nonEmpty!==meta.frames*meta.directions*meta.actions.length)throw new Error(`Empty animation frames in ${key}`);
    fs.writeFileSync(path.join(out,key+'.png'),Buffer.from(png.split(',')[1],'base64'));
    fs.writeFileSync(path.join(out,key+'-team.png'),Buffer.from(mask.split(',')[1],'base64'));
    manifest[key]=meta;console.log('Baked '+key);
  }
  fs.writeFileSync(manifestPath,'// Generated by tools/art/bake-actors.mjs. Source and licenses: docs/ACTOR_ASSETS.md.\nconst ACTOR_ART = '+JSON.stringify(manifest,null,1)+';\n');
  if(only<0)for(const kind of ['cow','horse','wolf','deer']){
    const data=await page.evaluate(k=>window.exportAnimal(k),kind);
    fs.writeFileSync(path.join(root,'assets/thirdparty/quaternius/animals',kind[0].toUpperCase()+kind.slice(1)+'.glb'),Buffer.from(data,'base64'));
  }
  console.log(`Saved ${keys.length} animated actor atlases.`);
}finally{await browser?.close();server.close();}
