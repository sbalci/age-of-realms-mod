// Pure helpers for tools/art/bake-kenney.mjs: command-line options and manifest.js read/merge/write.
export const MANIFEST_HEADER = '// Generated by tools/art/bake-kenney.mjs from Kenney CC0 kits (assets/thirdparty/kenney), the original kit (assets/original) and processed generated landmarks. Do not edit.\n';

// --preview [a,b] renders a contact sheet; --recipes a,b bakes just those recipes and merges them into manifest.js.
// (Not --only: npm run owns that flag and swallows it, which would turn a partial bake into a full one.)
const FLAGS = ['--preview', '--recipes'];
const NPM_HINT = ' - run it as: npm run art:bake -- --recipes a,b (the -- before the options is required)';
export function parseBakeArgs(argv, env = {}) {
  const unknown = argv.filter(a => a.startsWith('--') && !FLAGS.includes(a));
  if (unknown.length) throw new Error('unknown option ' + unknown.join(', ') + ' (use --preview [a,b] or --recipes a,b)' + NPM_HINT);
  // npm run without -- eats the options: bare values reach argv, the flag itself arrives as npm_config_*
  const bare = argv.filter((a, i) => !a.startsWith('--') && !FLAGS.includes(argv[i - 1]));
  if (bare.length) throw new Error('unexpected argument ' + bare.join(', ') + NPM_HINT);
  if (env.npm_config_recipes || env.npm_config_preview) throw new Error('npm swallowed the bake options' + NPM_HINT);
  const list = flag => { const i = argv.indexOf(flag); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1].split(',') : null; };
  const preview = argv.includes('--preview');
  const only = preview ? list('--preview') : list('--recipes');
  if (!preview && argv.includes('--recipes') && !only) throw new Error('--recipes needs a comma-separated list of recipe names');
  return { preview, only };
}
export function parseManifest(src) {
  const m = /const KENNEY_ART = (\{[\s\S]*\});/.exec(src);
  return m ? JSON.parse(m[1]) : {};
}
export function serializeManifest(art) {
  return MANIFEST_HEADER + 'const KENNEY_ART = ' + JSON.stringify(art, null, 1) + ';\n';
}
// existing keys keep their order (re-baked ones are updated in place); new keys are appended
export function mergeManifest(existing, baked) {
  return { ...existing, ...baked };
}
